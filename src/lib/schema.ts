import { pgTable, text, timestamp, boolean, integer, jsonb, uniqueIndex } from 'drizzle-orm/pg-core';
import { sql } from 'drizzle-orm';
import { APP_VERSION } from './version';

// App instance (single row)
export const appInstance = pgTable('app_instance', {
  id: text('id').primaryKey().$default(() => 'instance_1'),
  createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  initializedAt: timestamp('initialized_at', { withTimezone: true }),
  version: text('version').notNull().default(APP_VERSION),
});

// UI admin token. `source` records who owns the credential:
//   'deploy' — auto-generated by deploy initialization (rotated each deploy)
//   'env'    — loaded from PCP_ADMIN_TOKEN (the env var owns it)
//   'user'   — set by the admin in Settings (never auto-rotated)
export const uiAuth = pgTable('ui_auth', {
  id: text('id').primaryKey().$default(() => 'ui_1'),
  tokenHash: text('token_hash').notNull(),
  salt: text('salt').notNull(),
  source: text('source', { enum: ['deploy', 'env', 'user'] }).notNull().default('deploy'),
  createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  updatedAt: timestamp('updated_at', { withTimezone: true }).notNull().defaultNow(),
  lastUsedAt: timestamp('last_used_at', { withTimezone: true }),
});

// Casdoor users (migration 011). One row per (issuer, sub). `groupsJson` is the
// groups snapshot from the last login and `isAdmin` is derived from the admin
// group at that login.
export const users = pgTable('users', {
  id: text('id').primaryKey(),
  oidcIssuer: text('oidc_issuer').notNull(),
  oidcSub: text('oidc_sub').notNull(),
  displayName: text('display_name').notNull(),
  email: text('email'),
  groupsJson: jsonb('groups_json').notNull().default([]),
  isAdmin: boolean('is_admin').notNull().default(false),
  createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  lastLoginAt: timestamp('last_login_at', { withTimezone: true }),
});

// Platform principals (e.g. `telegram:8627151333`) linked to a user. A
// principal links to at most one user.
export const identities = pgTable('identities', {
  principal: text('principal').primaryKey(),
  userId: text('user_id').notNull().references(() => users.id, { onDelete: 'cascade' }),
  linkMethod: text('link_method', { enum: ['claim', 'admin'] }).notNull(),
  linkedAt: timestamp('linked_at', { withTimezone: true }).notNull().defaultNow(),
});

// Single-use claim codes. Only the SHA-256 of the code is stored.
export const claims = pgTable('claims', {
  id: text('id').primaryKey(),
  codeHash: text('code_hash').notNull(),
  sessionId: text('session_id').notNull().references(() => sessions.id, { onDelete: 'cascade' }),
  principal: text('principal').notNull(),
  createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  expiresAt: timestamp('expires_at', { withTimezone: true }).notNull(),
  redeemedBy: text('redeemed_by').references(() => users.id, { onDelete: 'set null' }),
  redeemedAt: timestamp('redeemed_at', { withTimezone: true }),
});

// Claim redemption attempts, for per-user rate limiting.
export const claimAttempts = pgTable('claim_attempts', {
  id: text('id').primaryKey(),
  userId: text('user_id').notNull().references(() => users.id, { onDelete: 'cascade' }),
  succeeded: boolean('succeeded').notNull(),
  attemptedAt: timestamp('attempted_at', { withTimezone: true }).notNull().defaultNow(),
});

// Browser login sessions. The cookie carries a random id; only its SHA-256 is
// stored, together with the SHA-256 of the session's CSRF token.
export const webSessions = pgTable('web_sessions', {
  idHash: text('id_hash').primaryKey(),
  userId: text('user_id').notNull().references(() => users.id, { onDelete: 'cascade' }),
  csrfHash: text('csrf_hash').notNull(),
  createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  expiresAt: timestamp('expires_at', { withTimezone: true }).notNull(),
  lastSeenAt: timestamp('last_seen_at', { withTimezone: true }),
});

// In-flight OIDC authorization requests (state, nonce, PKCE verifier), keyed by
// the SHA-256 of a random value held in a short-lived browser cookie.
export const oidcLoginStates = pgTable('oidc_login_states', {
  idHash: text('id_hash').primaryKey(),
  state: text('state').notNull(),
  nonce: text('nonce').notNull(),
  codeVerifier: text('code_verifier').notNull(),
  returnTo: text('return_to').notNull().default('/dashboard'),
  createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  expiresAt: timestamp('expires_at', { withTimezone: true }).notNull(),
});

// Topics
export const topics = pgTable('topics', {
  id: text('id').primaryKey(),
  externalKey: text('external_key'),
  title: text('title').notNull(),
  description: text('description'),
  archived: boolean('archived').notNull().default(false),
  createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  updatedAt: timestamp('updated_at', { withTimezone: true }).notNull().defaultNow(),
}, (table) => ({
  externalKeyIdx: uniqueIndex('topics_external_key_idx').on(table.externalKey),
}));

// Sessions. `topicId` is nullable: a session may be uncategorized (no topic).
// `public` exposes a read-only view without the admin UI token.
export const sessions = pgTable('sessions', {
  id: text('id').primaryKey(),
  externalKey: text('external_key'),
  topicId: text('topic_id').references(() => topics.id),
  title: text('title').notNull(),
  // Recording mode the agent is told to honor: 'wild' (default) lets the agent
  // redact secrets it judges unsafe; 'exact' asks for verbatim recording
  // (including credentials) for faithful task migration.
  mode: text('mode', { enum: ['wild', 'exact'] }).notNull().default('wild'),
  public: boolean('public').notNull().default(false),
  archived: boolean('archived').notNull().default(false),
  createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  updatedAt: timestamp('updated_at', { withTimezone: true }).notNull().defaultNow(),
  lastMessageAt: timestamp('last_message_at', { withTimezone: true }),
  // Identity (migration 011). `ownerUserId` is the Casdoor user that owns the
  // session (null = unowned, admin-only). `principal` is the platform identity
  // the session belongs to (e.g. `telegram:123`). `class` is 'trusted' (a
  // verified one-to-one identity), 'unattributed' (no verified identity) or
  // 'group' (shared group chat; admin-only, never claimable).
  ownerUserId: text('owner_user_id').references(() => users.id, { onDelete: 'set null' }),
  principal: text('principal'),
  sessionClass: text('class', { enum: ['trusted', 'unattributed', 'group'] }).notNull().default('unattributed'),
}, (table) => ({
  externalKeyIdx: uniqueIndex('sessions_external_key_idx').on(table.externalKey),
}));

// Session tokens
export const sessionTokens = pgTable('session_tokens', {
  id: text('id').primaryKey(),
  sessionId: text('session_id')
    .notNull()
    .references(() => sessions.id),
  tokenHash: text('token_hash').notNull(),
  salt: text('salt').notNull(),
  name: text('name').notNull(),
  canRenameSession: boolean('can_rename_session').notNull().default(false),
  revoked: boolean('revoked').notNull().default(false),
  createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  expiresAt: timestamp('expires_at', { withTimezone: true }),
  lastUsedAt: timestamp('last_used_at', { withTimezone: true }),
  tokenPrefix: text('token_prefix'), // First 16 chars for quick lookup
});

// Scoped tokens: the unified token layer managed by the global token manager.
// `scope` bounds the token ('global' = full, 'folder' = one topic, 'session' =
// one session); `permissionsJson` carries fine-grained flags (see scoped-token.ts).
export const scopedTokens = pgTable('scoped_tokens', {
  id: text('id').primaryKey(),
  tokenHash: text('token_hash').notNull(),
  salt: text('salt').notNull(),
  tokenPrefix: text('token_prefix'),
  name: text('name').notNull(),
  scope: text('scope', { enum: ['global', 'folder', 'session'] }).notNull(),
  folderId: text('folder_id').references(() => topics.id),
  sessionId: text('session_id').references(() => sessions.id),
  permissionsJson: jsonb('permissions_json').default({}),
  revoked: boolean('revoked').notNull().default(false),
  createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  expiresAt: timestamp('expires_at', { withTimezone: true }),
  lastUsedAt: timestamp('last_used_at', { withTimezone: true }),
});

// Session-to-session links: an undirected, optionally labelled relationship so
// a model (or human) can connect related conversations (e.g. a DSH session and
// the PCP session that records it). `sessionA`/`sessionB` are stored in a
// normalized order (A <= B) by the write path.
export const sessionLinks = pgTable('session_links', {
  id: text('id').primaryKey(),
  sessionA: text('session_a').notNull().references(() => sessions.id),
  sessionB: text('session_b').notNull().references(() => sessions.id),
  label: text('label'),
  createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
});

// Messages
export const messages = pgTable('messages', {
  id: text('id').primaryKey(),
  sessionId: text('session_id')
    .notNull()
    .references(() => sessions.id),
  // Denormalized from the session; null when the session has no topic.
  topicId: text('topic_id').references(() => topics.id),
  ordinal: integer('ordinal').notNull(),
  role: text('role', { enum: ['user', 'assistant', 'system', 'tool', 'correction'] }).notNull(),
  content: text('content').notNull(),
  contentType: text('content_type', { enum: ['text', 'markdown', 'json'] }).notNull().default('markdown'),
  provider: text('provider'),
  BaseModel: text('base_model'),
  providerTimestamp: timestamp('provider_timestamp', { withTimezone: true }),
  observedAt: timestamp('observed_at', { withTimezone: true }).notNull(),
  sourceJson: jsonb('source_json'),
  metadataJson: jsonb('metadata_json').default({}),
  createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
});

// Compactions: durable session summaries stored alongside (never replacing)
// raw messages, for when full message upload is impossible.
export const compactions = pgTable('compactions', {
  id: text('id').primaryKey(),
  sessionId: text('session_id')
    .notNull()
    .references(() => sessions.id),
  summary: text('summary').notNull(),
  timelineJson: jsonb('timeline_json'),
  decisionsJson: jsonb('decisions_json'),
  requirementsJson: jsonb('requirements_json'),
  openQuestionsJson: jsonb('open_questions_json'),
  artifactsJson: jsonb('artifacts_json'),
  warningsJson: jsonb('warnings_json'),
  provider: text('provider'),
  baseModel: text('base_model'),
  createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  metadataJson: jsonb('metadata_json').default({}),
});

// Events
export const events = pgTable('events', {
  id: text('id').primaryKey(),
  sessionId: text('session_id').references(() => sessions.id),
  topicId: text('topic_id').references(() => topics.id),
  action: text('action').notNull(),
  actor: text('actor').notNull(),
  detailsJson: jsonb('details_json').default({}),
  createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
});

// Schema migrations
export const schemaMigrations = pgTable('schema_migrations', {
  version: text('version').primaryKey(),
  appliedAt: timestamp('applied_at', { withTimezone: true }).notNull().defaultNow(),
  checksum: text('checksum'),
});
