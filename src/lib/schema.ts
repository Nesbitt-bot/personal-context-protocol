// Scoped tokens: the unified token layer managed by the global token manager.
// `scope` bounds the token ('global' = full, 'folder' = one topic, 'session' =
// one session); `permissionsJson` carries fine-grained flags (see scoped-token.ts).
export const scopedTokens = pgTable('scoped_tokens', {
  id: text('id').primaryKey(),
  tokenHash: text('token_hash').notNull(),
  salt: text('salt').notNull(),
  tokenPrefix: text('token_prefix'),
  name: text('name').notNull(),
  scope: text('scope', { enum: ['global', 'folder', 'session'] }).notNull(),
  folderId: text('folder_id').references(() => topics.id),
  sessionId: text('session_id').references(() => sessions.id),
  permissionsJson: jsonb('permissions_json').default({}),
  revoked: boolean('revoked').notNull().default(false),
  createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  expiresAt: timestamp('expires_at', { withTimezone: true }),
  lastUsedAt: timestamp('last_used_at', { withTimezone: true }),
});

// Session-to-session links: an undirected, optionally labelled relationship so
// a model (or human) can connect related conversations (e.g. a DSH session and
// the PCP session that records it). `sessionA`/`sessionB` are stored in a
// normalized order (A <= B) by the write path.
export const sessionLinks = pgTable('session_links', {
  id: text('id').primaryKey(),
  sessionA: text('session_a').notNull().references(() => sessions.id),
  sessionB: text('session_b').notNull().references(() => sessions.id),
  label: text('label'),
  createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
});

// Messages
